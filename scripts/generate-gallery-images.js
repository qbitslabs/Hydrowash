import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const galleryDir = path.join(__dirname, '../public/images/gallery');
const outputFile = path.join(__dirname, '../src/data/galleryImagesAuto.ts');

const categoryFolders = ['ppf', 'ceramic',  'detailing', 'interior', 'wash','restoration'];

function scanGalleryFolder() {
  const images = [];

  const supportedExtensions = new Set([
    '.webp',
    '.jpg',
    '.jpeg',
    '.png',
  ]);

  for (const category of categoryFolders) {
    const categoryPath = path.join(galleryDir, category);

    if (!fs.existsSync(categoryPath)) {
      console.warn(`Category folder not found: ${category}`);
      continue;
    }

    for (const file of fs.readdirSync(categoryPath)) {
      const extension = path.extname(file).toLowerCase();

      if (!supportedExtensions.has(extension)) {
        continue;
      }

      images.push({
        path: `/images/gallery/${category}/${file}`,
        category,
      });
    }
  }

  return images;
}

function generateGalleryImagesFile(imageList) {
  const sortedList = [...imageList].sort((a, b) =>
    a.path.localeCompare(b.path)
  );

  const fileContent = `// Auto-generated by scripts/generate-gallery-images.js

import type { GalleryImage } from './galleryData';

const categoryFolders = ['ppf', 'ceramic', 'detailing', 'interior','wash', 'restoration'] as const;

type Category = typeof categoryFolders[number];

const manualImageList: { path: string; category: Category }[] = [
${sortedList
  .map(
    ({ path, category }) =>
      `  { path: '${path}', category: '${category}' },`
  )
  .join('\n')}
];

const BEFORE_REGEX = /-before$|-b4$/i;

function galleryImages(): GalleryImage[] {
  const images: GalleryImage[] = [];
  let id = 1;

  const categoryFiles: Record<string, typeof manualImageList> = {};

  for (const image of manualImageList) {
    (categoryFiles[image.category] ??= []).push(image);
  }

  for (const [category, items] of Object.entries(categoryFiles)) {
    const pairs = new Map<string, { before?: string; after?: string }>();

    for (const { path } of items) {
      const filename = path.split('/').pop() ?? '';
      const name = filename.replace(/\\.(webp|jpg|jpeg|png)$/i, '');

      const isBefore = BEFORE_REGEX.test(name);
      const baseName = isBefore
        ? name.replace(BEFORE_REGEX, '')
        : name;

      const pair = pairs.get(baseName) ?? {};

      if (isBefore) {
        pair.before = path;
      } else {
        pair.after = path;
      }

      pairs.set(baseName, pair);
    }

    for (const [name, pair] of pairs) {
      const src = pair.after ?? pair.before;

      if (!src) continue;

      images.push({
        id: id++,
        src,
        before:
          pair.before && pair.after
            ? pair.before
            : undefined,
        alt: formatAltText(name),
        category: category as Category,
      });
    }
  }

  return images;
}

function formatAltText(filename: string): string {
  return filename
    .replace(/[-_]/g, ' ')
    .replace(/\\b\\w/g, c => c.toUpperCase());
}

export const dynamicGalleryImages = galleryImages();

export const fallbackGalleryImages: GalleryImage[] = [
  // Your fallback images...
];

export const autoGalleryImages =
  dynamicGalleryImages.length
    ? dynamicGalleryImages
    : fallbackGalleryImages;
`;

  fs.writeFileSync(outputFile, fileContent, 'utf8');

  console.log(
    `Generated galleryImagesAuto.ts with ${sortedList.length} images`
  );
}

// Run the script
const imageList = scanGalleryFolder();
generateGalleryImagesFile(imageList);
console.log('Gallery image generation complete!');
